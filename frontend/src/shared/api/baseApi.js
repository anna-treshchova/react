import { createApi, fetchBaseQuery } from '@reduxjs/toolkit/query/react';
const  { VITE_BASE_URL: BASE_URL } = import.meta.env;
import { removeFromStorage } from '../lib/storage.js';

const baseQuery = fetchBaseQuery({
    baseUrl: BASE_URL,
    prepareHeaders: (headers, { getState }) => {
        const token = getState().auth?.accessToken;

        if (token) {
            headers.set('Authorization', `Bearer ${token}`);
        }
        return headers;
    }
})

const baseQueryWishAuth = async (arg, api, extraOptions) => {
    const result = await baseQuery(arg, api, extraOptions);

    if (result.error?.status === 401) {
        removeFromStorage(['access_token', 'recent_search']);
        api.dispatch(baseApi.util.resetApiState())
    }
    return result;
}

export const baseApi = createApi({
    reducerPath: 'api',
    baseQuery: baseQueryWishAuth,
    tagTypes: ['Hotels', 'HotelDetails'],
    endpoints: () => ({}),
})


